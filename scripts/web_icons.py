"""Writes web/icons.js from Lucide's SVG files, so the web client ships its icons inline and needs no icon package at run time.

    npm pack lucide-static && tar -xzf lucide-static-*.tgz
    python3 -I scripts/web_icons.py package/icons package/package.json

Lucide is ISC licensed (https://lucide.dev/license); see docs/SOURCES.md.
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

# our name -> Lucide's file name. The UI uses the names on the left.
ICONS = {
    "plus": "plus", "minus": "minus", "dots": "ellipsis", "search": "search", "folder": "folder", "home": "house",
    "gear": "settings", "bookmark": "bookmark", "check": "check", "x": "x", "clock": "clock", "alert": "circle-alert",
    "list": "list-todo", "chip": "cpu", "cloud": "cloud", "doc": "file-text", "image": "image", "video": "video",
    "film": "clapperboard", "code": "code", "terminal": "square-terminal", "pen": "pen-line", "globe": "globe",
    "chat": "message-square", "target": "target", "clip": "paperclip", "send": "arrow-up", "stop": "square",
    "left": "chevron-left", "right": "chevron-right", "down": "chevron-down", "panel": "panel-right", "trash": "trash-2",
    "refresh": "refresh-cw", "link": "link", "shield": "shield", "eyeoff": "eye-off", "play": "play", "spark": "sparkles",
    "wrench": "wrench", "tasks": "list-checks",
    "mic": "mic", "volume": "volume-2", "voice": "audio-lines",
    # devices
    "bulb": "lightbulb", "air": "air-vent", "fan": "fan", "blinds": "blinds", "lock": "lock", "unlocked": "lock-open",
    "plug": "plug", "power": "power", "speaker": "speaker", "robot": "bot", "thermometer": "thermometer", "camera": "cctv",
}
KEEP = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "width", "height", "points"}
SHAPES = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}

TEMPLATE = '''// Icons from Lucide %(version)s (https://lucide.dev, ISC licence), inlined so the client needs no icon package.
// Generated by scripts/web_icons.py — change the list there and run it again; do not edit the shapes by hand.
const NS = 'http://www.w3.org/2000/svg';

const SHAPES = %(shapes)s;

function draw(name, size, stroke) {
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', String(stroke));
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.classList.add('icon');
  for (const [tag, attrs] of SHAPES[name] || SHAPES.spark) {
    const shape = document.createElementNS(NS, tag);
    for (const key of Object.keys(attrs)) shape.setAttribute(key, attrs[key]);
    svg.append(shape);
  }
  return svg;
}

/** icon('folder') -> an inline SVG that inherits the text colour. `stroke` is the line weight in pixels when drawn at 16px. */
export function icon(name, size = 16, stroke = 1.5) {
  return draw(name, size, stroke * 1.5);
}

const TOOLS = [
  [/search|web|fetch|browse|open_url/, 'globe'], [/save_file|append_file|edit_file|write/, 'pen'], [/read_file|list_files|file/, 'doc'],
  [/shell|command|run/, 'terminal'], [/image/, 'image'], [/video|frames/, 'video'], [/drama/, 'film'], [/plan|goal/, 'target'],
  [/memor|recall|remember/, 'bookmark'], [/home|device/, 'home'], [/code|project/, 'code'], [/job/, 'clock'],
];
/** The icon for a tool call, by tool name. */
export function toolIcon(name) {
  const key = String(name || '').toLowerCase();
  for (const [pattern, id] of TOOLS) if (pattern.test(key)) return id;
  return 'wrench';
}

const DEVICES = { light: 'bulb', switch: 'power', outlet: 'plug', climate: 'air', cover: 'blinds', lock: 'lock', unlocked: 'unlocked', fan: 'fan', media: 'speaker', vacuum: 'robot', sensor: 'thermometer', camera: 'camera', scene: 'spark', other: 'home' };
export const deviceIcon = (type) => DEVICES[type] || DEVICES.other;
/** A device's icon at tile size: glyph('light', 24). */
export function glyph(type, size = 24, stroke = 1.5) {
  return draw(deviceIcon(type), size, stroke);
}

export function fileIcon(name, mime = '') {
  if (mime.startsWith('image')) return 'image';
  if (mime.startsWith('video')) return 'video';
  return /\\.(py|js|ts|swift|sh|json|html|css|go|rs|c|cpp|java)$/i.test(String(name || '')) ? 'code' : 'doc';
}
'''


def shapes(path):
    out = []
    for node in ET.parse(path).getroot().iter():
        tag = node.tag.split("}")[-1]
        if tag in SHAPES:
            out.append([tag, {k: v for k, v in node.attrib.items() if k in KEEP}])
    return out


def main():
    folder, package = Path(sys.argv[1]), Path(sys.argv[2])
    missing = [lucide for lucide in ICONS.values() if not (folder / f"{lucide}.svg").is_file()]
    if missing:
        sys.exit("Lucide has no icon named: " + ", ".join(missing))
    table = {name: shapes(folder / f"{lucide}.svg") for name, lucide in ICONS.items()}
    lines = ",\n".join(f"  {json.dumps(name)}: {json.dumps(value, separators=(',', ':'))}" for name, value in table.items())
    target = Path(__file__).resolve().parent.parent / "web" / "icons.js"
    target.write_text(TEMPLATE % {"version": json.loads(package.read_text())["version"], "shapes": "{\n" + lines + ",\n}"})
    print(f"wrote {target} with {len(table)} icons")


if __name__ == "__main__":
    main()
